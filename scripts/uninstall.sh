    [ -z "$BASE_IMAGES" ] || say "That counts $(count_lines "$BASE_IMAGES") base image(s) nothing else on this machine uses: $(printf '%s' "$BASE_IMAGES" | tr '\n' ' ')"
    if [ -t 0 ]; then
        read -r -p "  Delete the images? [Y/n]: " answer || true
    else
