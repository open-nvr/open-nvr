# Remove the OpenNVR install in this folder, apps, data and footage included,
# so that ./start.sh is a fresh install again. Linux and macOS; on Windows
# use .\start.ps1 uninstall (scripts\uninstall.ps1).
#
#   ./start.sh uninstall                    show what goes, ask you to type the
#                                           confirmation, which it draws on the
#                                           screen, then remove it all
#   ./start.sh uninstall --dry-run          show what would go, change nothing
#   ./start.sh uninstall --yes              do not ask (for scripts; the same removal)
#   ./start.sh uninstall --keep-recordings  leave the footage for the next install
#   ./start.sh uninstall --keep-backups     leave ./backups (the updater's database dumps)
#   ./start.sh uninstall --keep-images      keep OpenNVR's own images for the next
#                                           install (otherwise you are asked, and
#                                           the default is to delete them)
#   ./start.sh uninstall --delete-images    delete them without asking
#   ./start.sh uninstall --project NAME     also a compose project of an install
#                                           whose folder is gone
#
# THE RULE: this machine may run other things, and nothing of theirs is
# touched. So everything is matched item by item, never by "unused":
#
#   container  its compose project is this install's AND it was started from
#              this folder or is named opennvr_* (every app the catalog
#              installs is: opennvr_attendly, opennvr_gate_watch, ...)
#   volume     <project>_opennvr_* (the database, keys, every app's settings
#              and data) or <project>_shared_frames
#   network    <project>_opennvr_* or <project>_default
#   image      ghcr.io/open-nvr/*, opennvr/*, one compose built for this
#              project (its label says so), or a <project>-* image one of the
#              containers above ran. With them go the third-party images this
#              install's compose files and Dockerfiles name (postgres, nginx,
#              nats, alpine, ...) when no other container runs them; Docker
#              refuses the rest, and so does the script. An image a container
#              of another stack runs is never touched.
#   footage    cam-<n>*, orphaned, .evidence, .hevc_cache under RECORDINGS_PATH;
#              anything else in that folder stays, and so does the folder.
#   host       the update runner and the host agent, only when they run from
#              this folder.
#
# No `docker ... prune` and no forced image or volume removal, ever: Docker's
# own refusal is what protects something another container still uses.
#
# .env and the database volume go together or not at all: a new .env beside
# the old volume gives a database that refuses the new password. So the files
# are only touched once every volume is confirmed gone.

# No -e: a failed removal is counted and reported, and the rest still runs.
set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(dirname "$SCRIPT_DIR")"
cd "$ROOT" || exit 1

SYSTEMD_DIR="${OPENNVR_SYSTEMD_DIR:-/etc/systemd/system}"
PLIST="$HOME/Library/LaunchAgents/org.opennvr.update.plist"
HOST_PLIST="$HOME/Library/LaunchAgents/org.opennvr.host.plist"
HOST_UNIT="opennvr-host.service"
# Generated by the installer, the launcher, the updater and the host agent.
FILES=".env mediamtx-certs nginx-certs agent-certs host-hardening
data/updates data/update-requests data/net-hints data/host-agent data/host-agent-key
bin/opennvr-host.exe bin/opennvr-host.old.exe bin/opennvr-host bin/opennvr-host.build bin/opennvr-host.old"

# DEL_IMAGES empty = not decided yet: the operator is asked, default yes.
DRY=0; YES=0; DEL_REC=1; DEL_BACKUPS=1; DEL_IMAGES=""; EXTRA_PROJECT=""
FAILED=0

say()  { printf '  %s\n' "$*"; }
ok()   { printf '  ✓ %s\n' "$*"; }
warn() { printf '  ! %s\n' "$*"; }
die()  { printf '  ✗ %s\n' "$*" >&2; exit 1; }
failed() { printf '  ✗ %s\n' "$*" >&2; FAILED=$((FAILED + 1)); }
indent() { sed 's/^/      /'; }

# A daemon that is down and a socket this user may not open both make the
# docker client exit 1, and only its stderr tells them apart. The fix differs:
# start the daemon, or join the docker group (not sudo: start.sh refuses it,
# because the files it writes would then belong to root). Prints the headline
# and, on later lines, the fix, and returns 0 when Docker is unusable;
# returns 1 and prints nothing when it answers.
docker_unavailable_reason() {
    local err user
    err=$(docker info 2>&1 >/dev/null) && return 1
    user=$(id -un)
    case "$err" in
        *"permission denied"*|*"Permission denied"*)
            printf 'Docker is running, but %s may not use it (permission denied on the Docker socket).\n' "$user"
            printf '      → Join the docker group, open a new shell (or log out and back in), then re-run:\n'
            printf '          sudo usermod -aG docker %s && newgrp docker\n' "$user"
            printf '      → Not sudo ./start.sh: .env and the certificates would then belong to root.\n' ;;
        *)
            printf 'Docker is not running.\n'
            printf '      → Start the Docker daemon, then re-run.\n' ;;
    esac
}

usage() { sed -n '5,20p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; }

while [ $# -gt 0 ]; do
    case "$1" in
        --dry-run) DRY=1 ;;
        --yes|-y) YES=1 ;;
        --keep-recordings) DEL_REC=0 ;;
        --keep-backups) DEL_BACKUPS=0 ;;
        --keep-images) DEL_IMAGES=0 ;;
        --delete-images) DEL_IMAGES=1 ;;
        --project) [ $# -ge 2 ] || die "--project needs a name"; EXTRA_PROJECT="$2"; shift ;;
        -h|--help) usage; exit 0 ;;
        *) die "unknown option: $1 (see --help)" ;;
    esac
    shift
done

case "$(uname -s)" in
    Linux*|Darwin*) ;;
    *) die "On Windows run .\\start.ps1 uninstall" ;;
esac
[ -f docker-compose.yml ] && [ -f start.sh ] || die "$ROOT is not an OpenNVR folder"
command -v docker >/dev/null 2>&1 || die "Docker is not installed, so its containers and volumes cannot be checked."
docker_reason=$(docker_unavailable_reason) && die "$docker_reason
      Nothing has been changed."

# An update in flight would bring the stack back up behind us. But the lock
# is also held by the update runner's own check, once a minute and for a
# minute or two after a version change, and refusing on that sent an
# operator away from a machine that was only looking for a release (a
# Ventuno Q, 2026-11-16). So: wait for the holder, then go on; refuse only
# if it is still there, and say how to stop the runner. A dry run changes
# nothing and waits for nothing.
LOCK_WAIT="${OPENNVR_UNINSTALL_LOCK_WAIT:-180}"
update_lock_pid() {
    local pid
    pid=$(cat data/updates/.lock/pid 2>/dev/null || true)
    if [ -n "$pid" ] && kill -0 "$pid" 2>/dev/null; then printf '%s' "$pid"; fi
}
wait_for_update() {
    local pid waited=0
    pid=$(update_lock_pid)
    [ -n "$pid" ] || return 0
    if [ "$DRY" = 1 ]; then
        warn "The update runner is busy (pid $pid). A real uninstall waits for it first."
        return 0
    fi
    say "The update runner is busy (pid $pid): its check can take a minute or two. Waiting, up to ${LOCK_WAIT} s ..."
    while [ "$waited" -lt "$LOCK_WAIT" ]; do
        sleep 2; waited=$((waited + 2))
        [ -n "$(update_lock_pid)" ] || return 0
    done
    pid=$(update_lock_pid)
    die "An update is still running (pid $pid) after ${LOCK_WAIT} s: nothing has been changed. If it is the update runner, stop it and run this again: ./start.sh auto-update disable"
}
wait_for_update

env_get() {
    grep -E "^$1=" .env 2>/dev/null | tail -n 1 | cut -d= -f2- \
        | sed -E 's/[[:space:]]+#.*$//; s/^"(.*)"$/\1/; s/^'"'"'(.*)'"'"'$/\1/' | tr -d '\r'
}

# Compose's own rule for a project name, from the folder unless it is set.
default_project() {
    local name="${COMPOSE_PROJECT_NAME:-$(env_get COMPOSE_PROJECT_NAME)}"
    [ -n "$name" ] || name="$(basename "$ROOT")"
    printf '%s' "$name" | tr '[:upper:]' '[:lower:]' | tr -cd 'a-z0-9_-' | sed -E 's/^[^a-z0-9]+//'
}

# Newline-delimited strings, not arrays: macOS ships bash 3.2, where an empty
# array under `set -u` is an error, and an empty list is a normal result here.
add_line() { if [ -n "$1" ]; then printf '%s\n%s' "$1" "$2"; else printf '%s' "$2"; fi; }
in_lines() { printf '%s\n' "$1" | grep -qxF -- "$2"; }
count_lines() { if [ -n "$1" ]; then printf '%s\n' "$1" | wc -l | tr -d ' '; else printf 0; fi; }
# "1.73GB" / "678MB" / "32.3kB", as docker images prints them, in whole MB.
size_mb() {
    printf '%s' "$1" | sed -E 's/^([0-9.]+) *([A-Za-z]*).*/\1 \2/' \
        | awk '{ v = $1 + 0; u = $2; if (u ~ /^T/) v *= 1048576; else if (u ~ /^G/) v *= 1024;
                 else if (u ~ /^k/) v /= 1024; else if (u ~ /^B/) v /= 1048576; printf "%d", v + 0.5 }'
}
mb_gb() { awk -v mb="$1" 'BEGIN { printf "%.1f GB", mb / 1024 }'; }
images_gb() { mb_gb $((IMAGES_MB + BASE_MB)); }
images_count() { echo $(( $(count_lines "$IMAGES") + $(count_lines "$BASE_IMAGES") )); }
# The plan's line about images: OpenNVR's own, and the base images with them.
images_line() {
    if [ -z "$IMAGES" ]; then
        printf 'Base images only OpenNVR pulled (%s, %s)' "$(count_lines "$BASE_IMAGES")" "$(mb_gb "$BASE_MB")"
    elif [ -z "$BASE_IMAGES" ]; then
        printf 'OpenNVR images (%s, %s)' "$(count_lines "$IMAGES")" "$(mb_gb "$IMAGES_MB")"
    else
        printf 'OpenNVR images (%s, %s) and base images nothing else uses (%s, %s)' \
            "$(count_lines "$IMAGES")" "$(mb_gb "$IMAGES_MB")" "$(count_lines "$BASE_IMAGES")" "$(mb_gb "$BASE_MB")"
    fi
}

# The third-party images this install names: `image:` lines of its compose
# files, FROM and COPY --from of its Dockerfiles (inline ones included), with
# ${VAR:-default} read as the default. Only exact repository:tag references.
pinned_images() {
    {
        cat "$ROOT"/docker-compose*.yml "$ROOT"/compose*.yml 2>/dev/null \
            | grep -E '^[[:space:]]*(-[[:space:]]*)?image:' | sed -E 's/^[^:]*image:[[:space:]]*//'
        cat "$ROOT"/Dockerfile "$ROOT"/*/Dockerfile "$ROOT"/examples/*/Dockerfile "$ROOT"/docker-compose*.yml 2>/dev/null \
            | grep -E '^[[:space:]]*(FROM[[:space:]]|COPY[[:space:]].*--from=)' \
            | sed -E 's/^[[:space:]]*FROM[[:space:]]+(--platform=[^[:space:]]+[[:space:]]+)?//; s/^[[:space:]]*COPY[[:space:]].*--from=//; s/[[:space:]].*$//'
    } | sed -E 's/[[:space:]]*#.*$//; s/["'"'"']//g; s/\$\{[A-Za-z_0-9]+:-([^{}]*)\}/\1/g; s/\$\{[A-Za-z_0-9]+:-([^{}]*)\}/\1/g; s/[[:space:]]+$//' \
      | grep -vE '\$|^(ghcr\.io/open-nvr/|opennvr/)' \
      | grep -E '^[a-z0-9][a-z0-9._/-]*(:[A-Za-z0-9._-]+)?(@sha256:[0-9a-f]+)?$' | grep -E '[:/]' | sort -u
}

# An image a container of another stack runs is never ours to remove.
used_elsewhere() { in_lines "$OTHER_USED" "$1" || in_lines "$OTHER_USED" "${1%:latest}"; }

collect() {
    local all name project workdir image p line
    all=$(docker ps -a --format '{{.Names}}|{{.Label "com.docker.compose.project"}}|{{.Label "com.docker.compose.project.working_dir"}}|{{.Image}}')

    PROJECTS="$(default_project)"
    [ -z "$EXTRA_PROJECT" ] || PROJECTS=$(add_line "$PROJECTS" "$EXTRA_PROJECT")
    while IFS='|' read -r name project workdir image; do
        if [ -n "$project" ] && [ "$workdir" = "$ROOT" ] && ! in_lines "$PROJECTS" "$project"; then
            PROJECTS=$(add_line "$PROJECTS" "$project")
        fi
    done <<< "$all"

    CONTAINERS=""; ELSEWHERE=""; USED_IMAGES=""; OTHER_USED=""
    while IFS='|' read -r name project workdir image; do
        [ -n "$name" ] || continue
        if [ -n "$project" ] && in_lines "$PROJECTS" "$project" \
           && { [ "$workdir" = "$ROOT" ] || [[ "$name" == opennvr_* ]]; }; then
            CONTAINERS=$(add_line "$CONTAINERS" "$name")
            USED_IMAGES=$(add_line "$USED_IMAGES" "$image")
        else
            OTHER_USED=$(add_line "$OTHER_USED" "$image")
            if [[ "$name" == opennvr_* ]]; then
                ELSEWHERE=$(add_line "$ELSEWHERE" "$name (project ${project:-none}, ${workdir:-no folder})")
            fi
        fi
    done <<< "$all"

    VOLUMES=""; NETWORKS=""
    while IFS= read -r p; do
        [ -n "$p" ] || continue
        while IFS= read -r line; do
            case "$line" in
                "${p}_opennvr_"*|"${p}_shared_frames") VOLUMES=$(add_line "$VOLUMES" "$line") ;;
            esac
        done <<< "$(docker volume ls --filter "label=com.docker.compose.project=$p" --format '{{.Name}}')"
        while IFS= read -r line; do
            case "$line" in
                "${p}_opennvr_"*|"${p}_default") NETWORKS=$(add_line "$NETWORKS" "$line") ;;
            esac
        done <<< "$(docker network ls --filter "label=com.docker.compose.project=$p" --format '{{.Name}}')"
    done <<< "$PROJECTS"

    # Images compose built for one of our projects, by compose's own label;
    # an untagged one (a rebuild left it) by its id.
    local labelled="" id
    while IFS= read -r p; do
        [ -n "$p" ] || continue
        while IFS='|' read -r line id size; do
            [ -n "$line" ] || continue
            [ "$line" != "<none>:<none>" ] || line="$id"
            labelled=$(add_line "$labelled" "$line")
        done <<< "$(docker images --filter "label=com.docker.compose.project=$p" --format '{{.Repository}}:{{.Tag}}|{{.ID}}|{{.Size}}')"
    done <<< "$PROJECTS"

    IMAGES=""; IMAGES_MB=0; BASE_IMAGES=""; BASE_MB=0
    local ours size pinned
    pinned="$(pinned_images)"
    while IFS='|' read -r line id size; do
        [ -n "$line" ] || continue
        [ "$line" != "<none>:<none>" ] || line="$id"
        used_elsewhere "$line" && continue
        ours=0
        in_lines "$labelled" "$line" && ours=1
        case "$line" in
            ghcr.io/open-nvr/*|opennvr/*) ours=1 ;;
            *)
                # A locally built <project>-<service>: only one this install ran.
                while IFS= read -r p; do
                    case "$line" in
                        "$p"-*) if in_lines "$USED_IMAGES" "${line%:latest}" || in_lines "$USED_IMAGES" "$line"; then
                                    ours=1
                                fi ;;
                    esac
                done <<< "$PROJECTS"
                ;;
        esac
        if [ "$ours" = 1 ]; then
            IMAGES=$(add_line "$IMAGES" "$line")
            IMAGES_MB=$((IMAGES_MB + $(size_mb "${size:-0}")))
        elif in_lines "$pinned" "$line"; then
            BASE_IMAGES=$(add_line "$BASE_IMAGES" "$line")
            BASE_MB=$((BASE_MB + $(size_mb "${size:-0}")))
        fi
    done <<< "$(docker images --format '{{.Repository}}:{{.Tag}}|{{.ID}}|{{.Size}}')"
}

recordings_root() {
    local dir
    dir=$(env_get RECORDINGS_PATH)
    dir="${dir:-./recordings}"
    case "$dir" in
        /*) printf '%s' "${dir%/}" ;;
        *) dir="${dir#./}"; printf '%s/%s' "$ROOT" "${dir%/}" ;;
    esac
}

# What OpenNVR writes directly under RECORDINGS_PATH, one path per line.
recordings_list() {
    local root="$1" path
    [ -d "$root" ] || return 0
    for path in "$root"/cam-[0-9]* "$root"/orphaned "$root"/.evidence "$root"/.hevc_cache; do
        [ -e "$path" ] && printf '%s\n' "$path"
    done
    return 0
}

# Everything else in that folder: it stays, and the operator is told.
recordings_others() {
    local root="$1" path base
    [ -d "$root" ] || return 0
    for path in "$root"/* "$root"/.[!.]*; do
        [ -e "$path" ] || continue
        base="$(basename "$path")"
        case "$base" in
            cam-[0-9]*|orphaned|.evidence|.hevc_cache) ;;
            *) printf '%s\n' "$base" ;;
        esac
    done
    return 0
}

existing_files() {
    local f
    for f in $FILES .env.tmp.*; do
        [ -e "$f" ] && printf '%s\n' "$f"
    done
    return 0
}

# The update runner, only if it runs from this folder: a timer of another
# OpenNVR folder is that install's.
runner_unit() {
    if [ -f "$SYSTEMD_DIR/opennvr-update.service" ] \
       && grep -qxF "WorkingDirectory=$ROOT" "$SYSTEMD_DIR/opennvr-update.service"; then
        printf 'systemd'
    elif [ -f "$PLIST" ] && grep -qF "<string>$ROOT</string>" "$PLIST"; then
        printf 'launchd'
    fi
}

# The host agent (USB webcams, host monitoring), the same way.
host_agent_unit() {
    if [ -f "$SYSTEMD_DIR/$HOST_UNIT" ] \
       && grep -qxF "WorkingDirectory=$ROOT" "$SYSTEMD_DIR/$HOST_UNIT"; then
        printf 'systemd'
    elif [ -f "$HOST_PLIST" ] && grep -qF "<string>$ROOT" "$HOST_PLIST"; then
        printf 'launchd'
    fi
}

priv() { if [ "$(id -u)" = 0 ]; then "$@"; else sudo "$@"; fi; }

show_list() {
    local title="$1" list="$2"
    [ -n "$list" ] || return 0
    say "$title ($(count_lines "$list")):"
    printf '%s\n' "$list" | indent
}

show_plan() {
    local rec_count
    rec_count=$(count_lines "$(recordings_list "$REC_ROOT")")
    printf '\n  This folder: %s\n\n  To be removed:\n' "$ROOT"
    show_list "Containers: OpenNVR and every installed app" "$CONTAINERS"
    show_list "Volumes: the database, keys, and every app's settings and data" "$VOLUMES"
    show_list "Networks" "$NETWORKS"
    show_list "Files in this folder" "$(existing_files)"
    case "$RUNNER" in
        systemd) say "The update runner: the opennvr-update systemd timer (asks for sudo)" ;;
        launchd) say "The update runner: the org.opennvr.update launchd job" ;;
    esac
    case "$HOST_AGENT" in
        systemd) say "The host agent: the $HOST_UNIT systemd service (asks for sudo)" ;;
        launchd) say "The host agent: the org.opennvr.host launchd job" ;;
    esac
    if [ -d host-hardening ] && command -v nft >/dev/null 2>&1; then
        say "The camera-VLAN firewall: nft table inet opennvr-vlan, if loaded (asks for sudo)"
    fi
    if [ "$rec_count" -gt 0 ]; then
        if [ "$DEL_REC" = 1 ]; then say "Footage in $REC_ROOT: $rec_count folder(s)"
        else say "Footage in $REC_ROOT: $rec_count folder(s) — KEPT (--keep-recordings)"; fi
    fi
    if [ -d backups ]; then
        if [ "$DEL_BACKUPS" = 1 ]; then say "Update backups in ./backups"
        else say "Update backups in ./backups — KEPT (--keep-backups)"; fi
    fi
    if [ -n "$IMAGES$BASE_IMAGES" ]; then
        case "$DEL_IMAGES" in
            1) say "$(images_line)" ;;
            0) say "$(images_line) — KEPT for the next install (--keep-images)" ;;
            *) say "$(images_line) — you are asked; the default is to delete them" ;;
        esac
        [ -z "$BASE_IMAGES" ] || say "  base images: $(printf '%s' "$BASE_IMAGES" | tr '\n' ' ')"
    fi
    if [ -z "$CONTAINERS$VOLUMES$NETWORKS$(existing_files)$RUNNER$HOST_AGENT" ]; then
        say "(nothing: no OpenNVR install found for this folder)"
    fi
}

show_kept() {
    printf '\n  Left alone, always:\n'
    say "every other container, volume, network and image on this machine"
    say "any image a container of another stack runs, base images included"
    say "this source folder, and Ollama if it runs on this machine"
    local others extra_env
    others=$(recordings_others "$REC_ROOT")
    [ -z "$others" ] || say "other files in $REC_ROOT: $(printf '%s' "$others" | tr '\n' ' ')"
    extra_env=$(ls -a 2>/dev/null | grep -E '^\.env\.' | grep -vE '^\.env\.(example|tmp\.)' | tr '\n' ' ')
    [ -z "$extra_env" ] || say "your own copies, which may hold secrets: $extra_env"
    if [ -n "$ELSEWHERE" ]; then
        printf '\n'
        warn "Containers named opennvr_* that belong to another folder or project stay:"
        printf '%s\n' "$ELSEWHERE" | indent
        warn "A new install here cannot start beside them: the names collide."
        warn "If that install is dead, re-run with --project <its project>."
    fi
}

# The warning, and the sentence the operator has to type. Footage kept means
# a shorter sentence: nobody types "recordings" for footage that stays.
confirm_phrase() {
    if [ "$DEL_REC" = 1 ]; then printf 'uninstall and remove all data and recordings'
    else printf 'uninstall and remove all data'; fi
}

show_warning() {
    local rec_count
    rec_count=$(count_lines "$(recordings_list "$REC_ROOT")")
    printf '\n  ============================================================\n'
    printf '  WARNING: this removes OpenNVR from this machine.\n'
    printf '  Gone for good:\n'
    say "  - the database: cameras, users, events, settings, API tokens, two-factor"
    say "  - every installed app, with its settings and data"
    say "  - the certificates and keys"
    [ "$DEL_REC" = 1 ] && [ "$rec_count" -gt 0 ] && say "  - all footage in $REC_ROOT ($rec_count folder(s))"
    [ "$DEL_BACKUPS" = 1 ] && [ -d backups ] && say "  - the update backups in ./backups"
    [ "$DEL_IMAGES" = 1 ] && [ -n "$IMAGES$BASE_IMAGES" ] && say "  - $(images_count) images ($(images_gb)): OpenNVR's and the base images only it uses; the next install downloads them again"
    printf '  There is no undo.\n'
    printf '  ============================================================\n'
}

# One line, lower-cased, inner whitespace squeezed, so a double space or a
# capital does not fail the operator who meant it.
normalise() { printf '%s' "$1" | tr '[:upper:]' '[:lower:]' | tr -s '[:space:]' ' ' | sed -E 's/^ //; s/ $//'; }

# The sentence is drawn, not printed, so it cannot be copied off the screen:
# the operator reads it and types it. Capitals in a 3x5 pixel font (M and W
# need five), two pixel rows to a terminal line with half blocks, wrapped by
# word to the terminal's width.
glyph_row() {   # letter, row 1-5 -> the row's pixels, # and .
    local row="$2" g
    case "$1" in
        a) g=".#. #.# ### #.# #.#" ;;  b) g="##. #.# ##. #.# ##." ;;
        c) g="### #.. #.. #.. ###" ;;  d) g="##. #.# #.# #.# ##." ;;
        e) g="### #.. ### #.. ###" ;;  f) g="### #.. ### #.. #.." ;;
        g) g="### #.. #.# #.# ###" ;;  h) g="#.# #.# ### #.# #.#" ;;
        i) g="### .#. .#. .#. ###" ;;  j) g="..# ..# ..# #.# ###" ;;
        k) g="#.# #.# ##. #.# #.#" ;;  l) g="#.. #.. #.. #.. ###" ;;
        m) g="#...# ##.## #.#.# #...# #...#" ;;
        n) g="### #.# #.# #.# #.#" ;;
        o) g="### #.# #.# #.# ###" ;;  p) g="### #.# ### #.. #.." ;;
        q) g="### #.# #.# ### ..#" ;;  r) g="##. #.# ##. #.# #.#" ;;
        s) g="### #.. ### ..# ###" ;;  t) g="### .#. .#. .#. .#." ;;
        u) g="#.# #.# #.# #.# ###" ;;  v) g="#.# #.# #.# #.# .#." ;;
        w) g="#...# #...# #.#.# ##.## #...#" ;;
        x) g="#.# #.# .#. #.# #.#" ;;
        y) g="#.# #.# .#. .#. .#." ;;  z) g="### ..# .#. #.. ###" ;;
        *) g="... ... ... ... ..." ;;
    esac
    # shellcheck disable=SC2086
    set -- $g
    shift $((row - 1))
    printf '%s' "$1"
}

# One pixel row of a line of words: a blank column between letters, two
# between words.
bitmap_row() {
    local i=0 ch out=""
    while [ "$i" -lt "${#1}" ]; do
        ch="${1:$i:1}"
        if [ "$ch" = " " ]; then out="$out.."; else out="$out$(glyph_row "$ch" "$2")."; fi
        i=$((i + 1))
    done
    printf '%s' "$out"
}

# Two pixel rows in one terminal line: ▀ top, ▄ bottom, █ both.
draw_pair() {
    local top="$1" bottom="$2" i=0 line="  " t b
    while [ "$i" -lt "${#top}" ]; do
        t="${top:$i:1}"; b="${bottom:$i:1}"
        if [ "$t" = "#" ] && [ "$b" = "#" ]; then line="$line█"
        elif [ "$t" = "#" ]; then line="$line▀"
        elif [ "$b" = "#" ]; then line="$line▄"
        else line="$line "; fi
        i=$((i + 1))
    done
    printf '%s\n' "$line"
}

draw_words() {   # one line of words, three terminal lines
    local r1 r2 r3 r4 r5
    r1=$(bitmap_row "$1" 1); r2=$(bitmap_row "$1" 2); r3=$(bitmap_row "$1" 3)
    r4=$(bitmap_row "$1" 4); r5=$(bitmap_row "$1" 5)
    draw_pair "$r1" "$r2"; draw_pair "$r3" "$r4"; draw_pair "$r5" "${r5//#/.}"
}

words_width() {   # columns a line of words takes
    local i=0 w=0
    while [ "$i" -lt "${#1}" ]; do
        case "${1:$i:1}" in
            " ") w=$((w + 2)) ;;
            m|w) w=$((w + 6)) ;;
            *)   w=$((w + 4)) ;;
        esac
        i=$((i + 1))
    done
    echo $((w - 1))
}

draw_sentence() {
    local cols limit line="" word
    cols=$(tput cols 2>/dev/null || echo 80)
    [ "$cols" -ge 40 ] 2>/dev/null || cols=80
    limit=$((cols - 3))
    for word in $1; do
        if [ -n "$line" ] && [ "$(words_width "$line $word")" -gt "$limit" ]; then
            draw_words "$line"; printf '\n'; line="$word"
        elif [ -n "$line" ]; then
            line="$line $word"
        else
            line="$word"
        fi
    done
    [ -z "$line" ] || draw_words "$line"
}

# Images hold no site data, so this is a choice, not part of the warning.
# Default yes: a clean machine is what most people mean by uninstall.
ask_images() {
    [ -z "$DEL_IMAGES" ] && [ -n "$IMAGES$BASE_IMAGES" ] || return 0
    local answer=""
    printf '\n'
    say "Also delete OpenNVR's $(images_count) images ($(images_gb))? They hold no site data;"
