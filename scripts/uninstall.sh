}

ask_confirmation() {
    local phrase answer=""
    phrase="$(confirm_phrase)"
    show_warning
    printf '\n'
    say "To go ahead, type the sentence drawn here (capitals do not matter):"
    printf '\n'
    draw_sentence "$phrase"
    printf '\n'
    if [ -t 0 ]; then
        read -r -p "  > " answer || true
    else
        IFS= read -r answer || true
        [ -n "$answer" ] || die "No terminal to ask on. Re-run with --yes, or look first with --dry-run."
    fi
    if [ "$(normalise "$answer")" != "$phrase" ]; then
        say "That is not the confirmation. Nothing changed."
        exit 1
    fi
}

# rm first. Footage and certs are written by containers as root on Linux, so
# fall back to a throwaway container from a base image already on this host
# (--pull never), which removes that one path and nothing else.
remove_path() {
    local path="$1" parent base helper
    rm -rf -- "$path" 2>/dev/null
    [ -e "$path" ] || [ -L "$path" ] || return 0
    parent="$(cd "$(dirname "$path")" && pwd)"
    base="$(basename "$path")"
    helper=$(docker images --format '{{.Repository}}:{{.Tag}}' | grep -E '^(postgres|alpine|nginx):' | head -n 1)
    if [ -n "$helper" ]; then
        docker run --rm --pull never --entrypoint sh -v "$parent:/p" "$helper" \
            -c 'rm -rf -- "/p/$1"' sh "$base" >/dev/null 2>&1
    fi
    if [ -e "$path" ]; then
        failed "could not remove $path (try: sudo rm -rf \"$path\")"
        return 1
    fi
}

remove_runner() {
    case "$RUNNER" in
        systemd)
            priv systemctl disable --now opennvr-update.timer >/dev/null 2>&1 || true
            if priv rm -f "$SYSTEMD_DIR/opennvr-update.service" "$SYSTEMD_DIR/opennvr-update.timer"; then
                priv systemctl daemon-reload >/dev/null 2>&1 || true
                ok "Update runner removed"
            else
                failed "could not remove the update runner: sudo ./start.sh auto-update disable"
            fi
            ;;
        launchd)
            launchctl unload -w "$PLIST" 2>/dev/null || true
            rm -f "$PLIST" && ok "Update runner removed"
            ;;
    esac
}

remove_host_agent() {
    case "$HOST_AGENT" in
        systemd)
            priv systemctl disable --now "$HOST_UNIT" >/dev/null 2>&1 || true
            if priv rm -f "$SYSTEMD_DIR/$HOST_UNIT"; then
                priv systemctl daemon-reload >/dev/null 2>&1 || true
                ok "Host agent removed"
            else
                failed "could not remove the host agent: ./start.sh host-agent uninstall"
            fi
            ;;
        launchd)
            launchctl unload "$HOST_PLIST" 2>/dev/null || true
            rm -f "$HOST_PLIST" && ok "Host agent removed"
            ;;
    esac
}

remove_firewall() {
    [ -d host-hardening ] || return 0
    command -v nft >/dev/null 2>&1 || return 0
    if priv nft list table inet opennvr-vlan >/dev/null 2>&1; then
        if priv nft delete table inet opennvr-vlan; then
            ok "Camera-VLAN firewall table removed"
        else
            failed "could not remove nft table inet opennvr-vlan: ./scripts/revert-camera-vlan-hardening.sh"
            KEEP_HARDENING=1
        fi
    fi
}

