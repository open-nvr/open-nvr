# Stop first, then remove. `docker rm -f` on a running container is a
# SIGKILL, and a process killed while it holds models on a Qualcomm NPU
# leaves its buffers in the kernel until the next reboot: measured on a
# Ventuno Q, 0.37 to 0.78 GB per killed adapter and nothing for one that
# was stopped (2026-11-16). A reinstall after a kill started with gigabytes
# of memory already gone. One `docker stop` for all of them, so they shut
# down side by side; a container that will not stop is still removed.
stop_list=()
while IFS= read -r item; do
    [ -n "$item" ] && stop_list+=("$item")
done <<< "$CONTAINERS"
if [ "${#stop_list[@]}" -gt 0 ]; then
    docker stop -t 20 "${stop_list[@]}" >/dev/null 2>&1 || true
fi
while IFS= read -r item; do
    [ -n "$item" ] || continue
    docker rm -f -v "$item" >/dev/null 2>&1 || failed "could not remove container $item"
done <<< "$CONTAINERS"
[ -z "$CONTAINERS" ] || ok "Containers removed"

while IFS= read -r item; do
    [ -n "$item" ] || continue
    docker volume rm "$item" >/dev/null 2>&1 || failed "could not remove volume $item (does another container use it?)"
done <<< "$VOLUMES"
while IFS= read -r item; do
    [ -n "$item" ] || continue
    docker network rm "$item" >/dev/null 2>&1 || warn "Network $item stays: something else is attached to it."
done <<< "$NETWORKS"

# Checked against Docker, not against the commands above returning 0.
LEFT_VOLUMES=""
while IFS= read -r item; do
    [ -n "$item" ] || continue
    if docker volume inspect "$item" >/dev/null 2>&1; then
        LEFT_VOLUMES=$(add_line "$LEFT_VOLUMES" "$item")
    fi
done <<< "$VOLUMES"
if [ -n "$LEFT_VOLUMES" ]; then
    failed "Some volumes are still there, so .env, the certs and the footage were kept (see the top of this script):"
    printf '%s\n' "$LEFT_VOLUMES" | indent
    say "Fix that and run this again."
    exit 1
fi
[ -z "$VOLUMES" ] || ok "Volumes removed"

remove_firewall
while IFS= read -r item; do
