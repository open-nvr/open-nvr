# Remove the OpenNVR install in this folder, apps, data and footage included,
# so that .\start.ps1 is a fresh install again. Same rules as
# scripts/uninstall.sh (read that header for why).
#
#   .\start.ps1 uninstall                    show what goes, ask you to type the
#                                            confirmation, which it draws on the
#                                            screen, then remove it all
#   .\start.ps1 uninstall --dry-run          show what would go, change nothing
#   .\start.ps1 uninstall --yes              do not ask (for scripts; the same removal)
#   .\start.ps1 uninstall --keep-recordings  leave the footage for the next install
#   .\start.ps1 uninstall --keep-backups     leave .\backups (the updater's database dumps)
#   .\start.ps1 uninstall --keep-images      keep OpenNVR's own images for the next
#                                            install (otherwise you are asked, and
#                                            the default is to delete them)
#   .\start.ps1 uninstall --delete-images    delete them without asking
#   .\start.ps1 uninstall --project NAME     also a compose project of an install
#                                            whose folder is gone
#
# THE RULE: this machine may run other things, and nothing of theirs is
# touched. Everything is matched item by item, never by "unused":
#
#   container  its compose project is this install's AND it was started from
#              this folder or is named opennvr_* (every app the catalog
#              installs is: opennvr_attendly, opennvr_gate_watch, ...)
#   volume     <project>_opennvr_* (the database, keys, every app's settings
#              and data) or <project>_shared_frames
#   network    <project>_opennvr_* or <project>_default
#   image      ghcr.io/open-nvr/*, opennvr/*, or a <project>-* image one of
#              the containers above ran. postgres, nginx, nats, alpine and the
#              like stay: another stack may need them.
#   footage    cam-<n>*, orphaned, .evidence, .hevc_cache under RECORDINGS_PATH;
#              anything else in that folder stays, and so does the folder.
#   host       the update runner and the host agent (Scheduled Tasks), only
#              when they run from this folder.
#
# No `docker ... prune` and no forced image or volume removal, ever. .env and
# the database volume go together or not at all, so the files are only touched
# once every volume is confirmed gone.
#
# Written for Windows PowerShell 5.1: every native command is checked through
# $LASTEXITCODE, and no --format has a double quote in it (5.1 does not escape
# those for a native command), which is why labels are parsed from {{.Labels}}.

$Root = Split-Path $PSScriptRoot -Parent
Set-Location $Root

$TaskName = "OpenNVR update runner"
$HostTaskName = "OpenNVR host agent"
# Generated by the installer, the launcher, the updater and the host agent.
$Files = @(".env", "mediamtx-certs", "nginx-certs", "agent-certs", "host-hardening",
           "data\updates", "data\update-requests", "data\net-hints", "data\host-agent", "data\host-agent-key",
           "bin\opennvr-host.exe", "bin\opennvr-host.old.exe", "bin\opennvr-host", "bin\opennvr-host.build")
$FootagePattern = '^(cam-\d.*|orphaned|\.evidence|\.hevc_cache)$'

# $DelImages $null = not decided yet: the operator is asked, default yes.
$Dry = $false; $Yes = $false; $DelRec = $true; $DelBackups = $true; $DelImages = $null
$ExtraProject = ""
$script:Failed = 0

function Write-Say($t)  { Write-Host "  $t" }
function Write-Ok($t)   { Write-Host "  OK $t" -ForegroundColor Green }
function Write-Warn2($t) { Write-Host "  ! $t" -ForegroundColor Yellow }
function Write-Fail($t) { Write-Host "  X $t" -ForegroundColor Red; $script:Failed++ }
function Stop-With($t)  { Write-Host "  X $t" -ForegroundColor Red; exit 1 }

for ($i = 0; $i -lt $args.Count; $i++) {
    switch -Exact ($args[$i]) {
        "--dry-run"           { $Dry = $true }
        "--yes"               { $Yes = $true }
        "-y"                  { $Yes = $true }
        "--keep-recordings"   { $DelRec = $false }
        "--keep-backups"      { $DelBackups = $false }
        "--keep-images"       { $DelImages = $false }
        "--delete-images"     { $DelImages = $true }
        "--project" {
            $i++
            if ($i -ge $args.Count) { Stop-With "--project needs a name" }
            $ExtraProject = $args[$i]
        }
        { $_ -in "-h", "--help" } {
            Get-Content $PSCommandPath -TotalCount 19 | Select-Object -Skip 3 | ForEach-Object { $_ -replace '^# ?', '' }
            exit 0
        }
        default { Stop-With "unknown option: $($args[$i]) (see --help)" }
    }
}

if ([Environment]::OSVersion.Platform -ne [PlatformID]::Win32NT) { Stop-With "On Linux and macOS run ./start.sh uninstall" }
if (-not ((Test-Path "docker-compose.yml") -and (Test-Path "start.ps1"))) { Stop-With "$Root is not an OpenNVR folder" }
if (-not (Get-Command docker -ErrorAction SilentlyContinue)) { Stop-With "Docker is not installed, so its containers and volumes cannot be checked." }
docker info *> $null
if ($LASTEXITCODE -ne 0) { Stop-With "Docker is not running. Start it and re-run: nothing has been changed." }

# An update in flight would bring the stack back up behind us.
$lockFile = "data\updates\.lock"
if (Test-Path $lockFile -PathType Leaf) {
    $lockPid = Get-Content $lockFile -ErrorAction SilentlyContinue
    if ($lockPid -and (Get-Process -Id ([int]$lockPid) -ErrorAction SilentlyContinue)) {
        Stop-With "An update is running (pid $lockPid). Wait for it to finish: nothing has been changed."
    }
}

function Get-EnvValue([string]$Key) {
    if (-not (Test-Path ".env")) { return "" }
    $hits = @(Get-Content ".env" -Encoding UTF8 | Where-Object { $_ -match "^$Key=" })
    if ($hits.Count -eq 0) { return "" }
    $value = ($hits[-1] -split '=', 2)[1] -replace '\s+#.*$', ''
    return $value.Trim().Trim('"').Trim("'")
}

# Compose's own rule for a project name, from the folder unless it is set.
function Get-DefaultProject {
    $name = $env:COMPOSE_PROJECT_NAME
    if (-not $name) { $name = Get-EnvValue "COMPOSE_PROJECT_NAME" }
    if (-not $name) { $name = Split-Path $Root -Leaf }
    return ($name.ToLower() -replace '[^a-z0-9_-]', '' -replace '^[^a-z0-9]+', '')
}

function Get-NormalPath([string]$Path) { return ($Path -replace '/', '\').TrimEnd('\') }

# "1.73GB" / "678MB" / "32.3kB", as docker images prints them, in MB.
function Get-SizeMB([string]$Text) {
    if ($Text -notmatch '^([\d.]+)\s*([kKMGT]?B)') { return 0 }
    $v = [double]$Matches[1]
    switch ($Matches[2].ToUpper()) { 'TB' { return $v * 1048576 } 'GB' { return $v * 1024 } 'MB' { return $v } 'KB' { return $v / 1024 } default { return $v / 1048576 } }
}
function Get-ImagesGB { return ('{0:N1} GB' -f ($Found.ImagesMB / 1024)) }

function Find-Install {
    $all = @(docker ps -a --format '{{.Names}}|{{.Image}}|{{.Labels}}') | Where-Object { $_ } | ForEach-Object {
        $parts = $_ -split '\|', 3
        $labels = if ($parts.Count -ge 3) { $parts[2] } else { "" }
        $project = if ($labels -match '(?:^|,)com\.docker\.compose\.project=([^,]*)') { $Matches[1] } else { "" }
        $workdir = if ($labels -match '(?:^|,)com\.docker\.compose\.project\.working_dir=([^,]*)') { $Matches[1] } else { "" }
        [pscustomobject]@{ Name = $parts[0]; Image = $parts[1]; Project = $project; WorkDir = $workdir }
    }
    $here = Get-NormalPath $Root

    $projects = @(Get-DefaultProject)
    if ($ExtraProject) { $projects += $ExtraProject }
    foreach ($c in @($all)) {
        if ($c -and $c.Project -and ((Get-NormalPath $c.WorkDir) -ieq $here) -and ($projects -notcontains $c.Project)) {
            $projects += $c.Project
        }
    }

    $containers = @(); $elsewhere = @(); $used = @()
    foreach ($c in @($all)) {
        if (-not $c) { continue }
        $fromHere = (Get-NormalPath $c.WorkDir) -ieq $here
        if ($c.Project -and ($projects -contains $c.Project) -and ($fromHere -or $c.Name -like "opennvr_*")) {
            $containers += $c.Name
            $used += $c.Image
        } elseif ($c.Name -like "opennvr_*") {
            $elsewhere += "$($c.Name) (project $($c.Project), $($c.WorkDir))"
        }
    }

    $volumes = @(); $networks = @()
    foreach ($p in $projects) {
        $q = [regex]::Escape($p)
        $volumes += @(docker volume ls --filter "label=com.docker.compose.project=$p" --format '{{.Name}}') |
            Where-Object { $_ -cmatch "^${q}_(opennvr_.*|shared_frames)$" }
        $networks += @(docker network ls --filter "label=com.docker.compose.project=$p" --format '{{.Name}}') |
            Where-Object { $_ -cmatch "^${q}_(opennvr_.*|default)$" }
    }

    $images = @(); $imagesMB = 0.0
    foreach ($row in @(docker images --format '{{.Repository}}:{{.Tag}}|{{.Size}}')) {
        if (-not $row) { continue }
        $parts = $row -split '\|', 2
        $line = $parts[0]; $size = if ($parts.Count -ge 2) { $parts[1] } else { '' }
        $ours = ($line -like "ghcr.io/open-nvr/*" -or $line -like "opennvr/*")
        if (-not $ours) {
            # A locally built <project>-<service>: only one this install ran.
            foreach ($p in $projects) {
                if ($line -like "$p-*" -and (($used -contains $line) -or ($used -contains ($line -replace ':latest$', '')))) { $ours = $true }
            }
        }
        if ($ours) { $images += $line; $imagesMB += Get-SizeMB $size }
    }

    return @{ Containers = @($containers); Elsewhere = @($elsewhere); Volumes = @($volumes); Networks = @($networks); Images = @($images); ImagesMB = $imagesMB }
}

function Get-RecordingsRoot {
    $dir = Get-EnvValue "RECORDINGS_PATH"
    if (-not $dir) { $dir = "./recordings" }
    if (-not [IO.Path]::IsPathRooted($dir)) { $dir = Join-Path $Root $dir }
    return [IO.Path]::GetFullPath($dir).TrimEnd('\')
}

# What OpenNVR writes directly under RECORDINGS_PATH.
function Get-Footage([string]$RecRoot) {
    if (-not (Test-Path -LiteralPath $RecRoot)) { return @() }
    return @(Get-ChildItem -LiteralPath $RecRoot -Force | Where-Object { $_.Name -match $FootagePattern })
}
# Everything else in that folder: it stays, and the operator is told.
function Get-NotFootage([string]$RecRoot) {
    if (-not (Test-Path -LiteralPath $RecRoot)) { return @() }
    return @(Get-ChildItem -LiteralPath $RecRoot -Force | Where-Object { $_.Name -notmatch $FootagePattern })
}

function Get-ExistingFiles {
    $found = @($Files | Where-Object { Test-Path -LiteralPath $_ })
    $found += @(Get-ChildItem -Force -Filter ".env.tmp.*" -ErrorAction SilentlyContinue | ForEach-Object { $_.Name })
    return $found
}

# A Scheduled Task of this folder's: a task of another OpenNVR folder is that install's.
function Get-FolderTask([string]$Name) {
    if (-not (Get-Command Get-ScheduledTask -ErrorAction SilentlyContinue)) { return $null }
    $task = Get-ScheduledTask -TaskName $Name -ErrorAction SilentlyContinue
    if (-not $task) { return $null }
    $here = Get-NormalPath $Root
    foreach ($action in @($task.Actions)) {
        if ($action.WorkingDirectory -and ((Get-NormalPath $action.WorkingDirectory) -ieq $here)) { return $task }
    }
    return $null
}

function Show-List([string]$Title, $List) {
    $items = @($List)
    if ($items.Count -eq 0) { return }
    Write-Say "$Title ($($items.Count)):"
    $items | ForEach-Object { Write-Host "      $_" }
}

function Show-Plan {
    $footage = @(Get-Footage $RecRoot)
    Write-Host ""
    Write-Host "  This folder: $Root"
    Write-Host ""
    Write-Host "  To be removed:"
    $files = @(Get-ExistingFiles)
    Show-List "Containers: OpenNVR and every installed app" $Found.Containers
    Show-List "Volumes: the database, keys, and every app's settings and data" $Found.Volumes
    Show-List "Networks" $Found.Networks
    Show-List "Files in this folder" $files
    if ($Runner) { Write-Say "The update runner: the scheduled task '$TaskName'" }
    if ($HostAgent) { Write-Say "The host agent: the scheduled task '$HostTaskName'" }
    if ($footage.Count -gt 0) {
        if ($DelRec) { Write-Say "Footage in ${RecRoot}: $($footage.Count) folder(s)" }
        else { Write-Say "Footage in ${RecRoot}: $($footage.Count) folder(s) - KEPT (--keep-recordings)" }
    }
    if (Test-Path "backups") {
        if ($DelBackups) { Write-Say "Update backups in .\backups" }
        else { Write-Say "Update backups in .\backups - KEPT (--keep-backups)" }
    }
    if ($Found.Images.Count -gt 0) {
        $n = "$($Found.Images.Count), $(Get-ImagesGB)"
        if ($DelImages -eq $true) { Write-Say "OpenNVR images ($n)" }
        elseif ($DelImages -eq $false) { Write-Say "OpenNVR images ($n) - KEPT for the next install (--keep-images)" }
        else { Write-Say "OpenNVR images ($n) - you are asked; the default is to delete them" }
    }
    if (($Found.Containers.Count + $Found.Volumes.Count + $Found.Networks.Count + $files.Count -eq 0) -and -not $Runner -and -not $HostAgent) {
        Write-Say "(nothing: no OpenNVR install found for this folder)"
    }
}

function Show-Kept {
    Write-Host ""
    Write-Host "  Left alone, always:"
    Write-Say "every other container, volume, network and image on this machine"
    Write-Say "shared base images (postgres, nginx, nats, alpine, ...)"
    Write-Say "this source folder, and Ollama if it runs on this machine"
    $others = @(Get-NotFootage $RecRoot | ForEach-Object { $_.Name })
    if ($others.Count -gt 0) { Write-Say "other files in ${RecRoot}: $($others -join ' ')" }
    $copies = @(Get-ChildItem -Force -Filter ".env.*" -ErrorAction SilentlyContinue |
        Where-Object { $_.Name -like ".env.*" -and $_.Name -ne ".env.example" -and $_.Name -notlike ".env.tmp.*" } | ForEach-Object { $_.Name })
    if ($copies.Count -gt 0) { Write-Say "your own copies, which may hold secrets: $($copies -join ' ')" }
    if ($Found.Elsewhere.Count -gt 0) {
        Write-Host ""
        Write-Warn2 "Containers named opennvr_* that belong to another folder or project stay:"
        $Found.Elsewhere | ForEach-Object { Write-Host "      $_" }
        Write-Warn2 "A new install here cannot start beside them: the names collide."
        Write-Warn2 "If that install is dead, re-run with --project <its project>."
    }
}

# The sentence the operator has to type. Footage kept means a shorter
# sentence: nobody types "recordings" for footage that stays.
function Get-ConfirmPhrase {
    if ($DelRec) { return "uninstall and remove all data and recordings" }
    return "uninstall and remove all data"
}

function Show-Warning {
    $footage = @(Get-Footage $RecRoot)
    Write-Host ""
    Write-Host "  ============================================================" -ForegroundColor Yellow
    Write-Host "  WARNING: this removes OpenNVR from this machine." -ForegroundColor Yellow
    Write-Host "  Gone for good:"
    Write-Say "  - the database: cameras, users, events, settings, API tokens, two-factor"
    Write-Say "  - every installed app, with its settings and data"
    Write-Say "  - the certificates and keys"
    if ($DelRec -and $footage.Count -gt 0) { Write-Say "  - all footage in $RecRoot ($($footage.Count) folder(s))" }
    if ($DelBackups -and (Test-Path "backups")) { Write-Say "  - the update backups in .\backups" }
    if ($DelImages -eq $true -and $Found.Images.Count -gt 0) { Write-Say "  - OpenNVR's $($Found.Images.Count) images ($(Get-ImagesGB)); the next install downloads them again" }
    Write-Host "  There is no undo." -ForegroundColor Yellow
    Write-Host "  ============================================================" -ForegroundColor Yellow
}

# Lower-cased, inner whitespace squeezed, so a double space or a capital
# does not fail the operator who meant it.
function Get-Normalised([string]$Text) { return (($Text -replace '\s+', ' ').Trim().ToLowerInvariant()) }

# The sentence is drawn, not printed, so it cannot be copied off the screen:
# the operator reads it and types it. Capitals in 3x5 cells, two columns a
# cell, wrapped by word to the window's width.
$Glyphs = @{
    "a" = ".#. #.# ### #.# #.#"; "b" = "##. #.# ##. #.# ##."; "c" = "### #.. #.. #.. ###"
    "d" = "##. #.# #.# #.# ##."; "e" = "### #.. ### #.. ###"; "f" = "### #.. ### #.. #.."
    "g" = "### #.. #.# #.# ###"; "h" = "#.# #.# ### #.# #.#"; "i" = "### .#. .#. .#. ###"
    "j" = "..# ..# ..# #.# ###"; "k" = "#.# #.# ##. #.# #.#"; "l" = "#.. #.. #.. #.. ###"
    "m" = "#.# ### ### #.# #.#"; "n" = "### #.# #.# #.# #.#"; "o" = "### #.# #.# #.# ###"
    "p" = "### #.# ### #.. #.."; "q" = "### #.# #.# ### ..#"; "r" = "##. #.# ##. #.# #.#"
    "s" = "### #.. ### ..# ###"; "t" = "### .#. .#. .#. .#."; "u" = "#.# #.# #.# #.# ###"
    "v" = "#.# #.# #.# #.# .#."; "w" = "#.# #.# ### ### #.#"; "x" = "#.# #.# .#. #.# #.#"
    "y" = "#.# #.# .#. .#. .#."; "z" = "### ..# .#. #.. ###"
}

# One line of words, five rows: 6 columns a letter, 1 between letters, 4 between words.
function Show-Words([string]$Words) {
    for ($row = 0; $row -lt 5; $row++) {
        $line = "  "
        foreach ($ch in $Words.ToCharArray()) {
            if ($ch -eq ' ') { $line += "    "; continue }
            $glyph = if ($Glyphs.ContainsKey("$ch")) { $Glyphs["$ch"] } else { "... ... ... ... ..." }
            $cell = ($glyph -split ' ')[$row]
            $line += ($cell -replace '#', '██' -replace '\.', '  ') + " "
        }
        Write-Host $line
    }
}

function Get-WordsWidth([string]$Words) {
    $spaces = @($Words.ToCharArray() | Where-Object { $_ -eq ' ' }).Count
    return ($Words.Length - $spaces) * 7 + $spaces * 4 - 1
}

function Show-Sentence([string]$Sentence) {
    $cols = 80
    try { $w = $Host.UI.RawUI.WindowSize.Width; if ($w -ge 40) { $cols = $w } } catch {}
    $limit = $cols - 3
    $line = ""
    foreach ($word in ($Sentence -split ' ')) {
        if ($line -and (Get-WordsWidth "$line $word") -gt $limit) { Show-Words $line; Write-Host ""; $line = $word }
        elseif ($line) { $line = "$line $word" }
        else { $line = $word }
    }
    if ($line) { Show-Words $line }
}

# Images hold no site data, so this is a choice, not part of the warning.
# Default yes: a clean machine is what most people mean by uninstall.
function Confirm-Images {
    if ($null -ne $DelImages -or $Found.Images.Count -eq 0) { return }
    Write-Host ""
    Write-Say "Also delete OpenNVR's $($Found.Images.Count) images ($(Get-ImagesGB))? They hold no site data;"
    Write-Say "the next install downloads them again."
    $answer = Read-Host "  Delete the images? [Y/n]"
    if ("$answer" -match '^\s*[Nn]') { $script:DelImages = $false; Write-Say "The images stay." }
    else { $script:DelImages = $true }
}

function Confirm-Uninstall {
    $phrase = Get-ConfirmPhrase
    Show-Warning
    Write-Host ""
    Write-Say "To go ahead, type the sentence drawn here (capitals do not matter):"
    Write-Host ""
    Show-Sentence $phrase
    Write-Host ""
    # Read-Host, redirected or not: [Console]::In.ReadLine() blocks on an
    # empty redirected stdin once a child process has run.
    $answer = Read-Host "  >"
    if ([Console]::IsInputRedirected -and -not $answer) {
        Stop-With "No terminal to ask on. Re-run with --yes, or look first with --dry-run."
    }
    if ((Get-Normalised $answer) -ne $phrase) {
        Write-Say "That is not the confirmation. Nothing changed."
        exit 1
    }
}

function Remove-Path([string]$Path) {
    Remove-Item -LiteralPath $Path -Recurse -Force -ErrorAction SilentlyContinue -Confirm:$false
    if (Test-Path -LiteralPath $Path) { Write-Fail "could not remove $Path (is a program holding a file in it open?)" }
}

function Remove-FolderTask([string]$Name, [string]$What, [string]$Hint) {
    try {
        Stop-ScheduledTask -TaskName $Name -ErrorAction SilentlyContinue
        Unregister-ScheduledTask -TaskName $Name -Confirm:$false -ErrorAction Stop
        Write-Ok "$What removed"
    } catch {
        Write-Fail "could not remove the ${What}: $Hint"
    }
}

$Found = Find-Install
$Runner = Get-FolderTask $TaskName
$HostAgent = Get-FolderTask $HostTaskName
$RecRoot = Get-RecordingsRoot

Show-Plan
Show-Kept
if ($Dry) {
    Write-Host ""
    Write-Host "  Dry run: nothing changed."
    exit 0
}

if ($Yes) {
    if ($null -eq $DelImages) { $DelImages = $true }
    Show-Warning
} else {
    Confirm-Images
    Confirm-Uninstall
}
Write-Host ""

# Host services first, so no tick brings anything back while the rest goes.
if ($Runner) { Remove-FolderTask $TaskName "Update runner" ".\start.ps1 auto-update disable" }
if ($HostAgent) { Remove-FolderTask $HostTaskName "Host agent" ".\start.ps1 host-agent uninstall" }

foreach ($item in $Found.Containers) {
    docker rm -f -v $item *> $null
    if ($LASTEXITCODE -ne 0) { Write-Fail "could not remove container $item" }
}
if ($Found.Containers.Count -gt 0) { Write-Ok "Containers removed" }

foreach ($item in $Found.Volumes) {
    docker volume rm $item *> $null
    if ($LASTEXITCODE -ne 0) { Write-Fail "could not remove volume $item (does another container use it?)" }
}
foreach ($item in $Found.Networks) {
    docker network rm $item *> $null
    if ($LASTEXITCODE -ne 0) { Write-Warn2 "Network $item stays: something else is attached to it." }
}

# Checked against Docker, not against the commands above returning 0.
$leftVolumes = @($Found.Volumes | Where-Object { docker volume inspect $_ *> $null; $LASTEXITCODE -eq 0 })
if ($leftVolumes.Count -gt 0) {
    Write-Fail "Some volumes are still there, so .env, the certs and the footage were kept (see scripts/uninstall.sh):"
    $leftVolumes | ForEach-Object { Write-Host "      $_" }
    Write-Say "Fix that and run this again."
    exit 1
}
if ($Found.Volumes.Count -gt 0) { Write-Ok "Volumes removed" }

foreach ($item in @(Get-ExistingFiles)) { Remove-Path (Join-Path $Root $item) }
Write-Ok "Generated files removed"

if ($DelRec) {
    foreach ($item in @(Get-Footage $RecRoot)) { Remove-Path $item.FullName }
    # Only when empty: anything else in there is not ours to remove.
    if ((Test-Path -LiteralPath $RecRoot) -and (@(Get-ChildItem -LiteralPath $RecRoot -Force).Count -eq 0)) {
        Remove-Item -LiteralPath $RecRoot -Force -ErrorAction SilentlyContinue -Confirm:$false
    }
    Write-Ok "Footage removed"
}

if ($DelBackups -and (Test-Path "backups")) {
    Remove-Path (Join-Path $Root "backups")
    if (-not (Test-Path "backups")) { Write-Ok "Update backups removed" }
}

if ($DelImages) {
    foreach ($item in $Found.Images) {
        # Never -f: Docker refuses while any other container uses the image.
        docker image rm $item *> $null
        if ($LASTEXITCODE -ne 0) { Write-Warn2 "Image $item stays: it is still in use." }
    }
    Write-Ok "OpenNVR images removed"
}

Write-Host ""
if (-not $DelRec -and (@(Get-Footage $RecRoot).Count -gt 0)) {
    Write-Say "Footage kept in $RecRoot. Give the next install the same folder: it moves"
    Write-Say "footage it has no camera for to orphaned\, and does not delete it."
}
if ($script:Failed -gt 0) {
    Write-Host "  X $($script:Failed) item(s) could not be removed; see above." -ForegroundColor Red
    exit 1
}
Write-Ok "OpenNVR is uninstalled from this folder. For a fresh install: .\start.ps1"
exit 0
